export function episodePacingGuidance(contract) {
  const { target, preferred, hard } = episodeDurationPolicy(contract);
  const margin = target.max < hard.max
    ? `超过 ${target.max} 秒至 ${hard.max} 秒仅作自然结尾余量，不能作为常态目标；处于这段余量时按具体对白、动作与结尾审读，语速或停顿意见作为非阻断提醒，不新增整集质量硬门。`
    : "";
  return `单集目标 ${target.min}–${target.max} 秒${preferred === null ? "" : `，常态 ${preferred} 秒`}；硬范围 ${hard.min}–${hard.max} 秒。${margin}超过 ${hard.max} 秒应在规划时沿已有情节自然增集，不通过加速口播、只缩数字或删核心戏压时长；实际超出硬范围沿现有预算门处理。`;
}
